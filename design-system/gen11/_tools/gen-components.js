/* COMPONENTS.md is the index of what the catalogue actually shows: every
   specimen, its selector, its context, its measured geometry and the chapter
   it lives in. Generated from the same extraction the catalogue is built from,
   so the document and the page can never disagree. */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../../..');
const FRAGS = process.env.FRAGS || 'C:/Users/Sigoff/AppData/Local/Temp/claude/c------WORK-AAN-CONTROL-PANEL/9fea96e9-7862-4244-9ba4-4dc3cf5b706e/scratchpad/frags.json';
const OUT = path.join(ROOT, 'design-system/gen11/COMPONENTS.md');

const frags = JSON.parse(fs.readFileSync(FRAGS, 'utf8'));
const ORDER = ['av','leads','lead','vehicle','queue','ticket','dealers','dealer-edit','accounting','login'];

const L = [];
const w = s => L.push(s);

let n = 0, groups = 0;
for (const k of ORDER) { const S = frags[k]; if (!S) continue;
  for (const g of S.groups) { groups++; n += g.items.filter(i => !i.missing).length; } }

w('# Gen 11 — COMPONENTS');
w('');
w('The index of what the catalogue shows. Every row is a specimen rendered in');
w('`index.html` from the product\'s own DOM and the product\'s own stylesheets.');
w('');
w('Generated by `_tools/gen-components.js` from the same extraction that builds');
w('the specimen hosts, so this document and the catalogue cannot disagree.');
w('');
w(`**${n} specimens** in **${groups} groups** across **${ORDER.filter(k => frags[k]).length} chapters**.`);
w('');
w('Geometry is measured at 1440×900. CONTEXT is the ancestor chain the component\'s');
w('CSS is scoped to — a leaf lifted out of it renders unstyled.');
w('');
w('---');
w('');

for (const k of ORDER) {
  const S = frags[k]; if (!S) continue;
  w(`## ${S.title}`);
  w('');
  w(`${S.role}`);
  w('');
  w(`Stack: \`${S.css.map(c => 'pages/' + c).join('\` + \`')}\` + \`pages/_aan-family.css\` + \`pages/_aan-components.css\``);
  w('');
  w(`Catalogue: [chapter](index.html#ch-${k}) · Host: \`specimens/${k}.html\` · Source page: \`pages/${S.page}\``);
  w('');
  for (const g of S.groups) {
    const items = g.items.filter(i => !i.missing);
    if (!items.length) continue;
    w(`### ${g.group}`);
    w('');
    w('| component | role | selector | box | padding | gap | radius |');
    w('|---|---|---|---|---|---|---|');
    for (const it of items) {
      const sel = it.tag + (it.cls ? '.' + it.cls.split(/\s+/).join('.') : '');
      w(`| **${it.name}** | ${it.role || '—'} | \`${sel}\` | ${it.box} | ${it.css.pad} | ${it.css.gap || '—'} | ${it.css.r} |`);
    }
    w('');
    for (const it of items) {
      if (!it.note) continue;
      w(`**${it.name}** — ${it.note}`);
      w('');
    }
  }
  w('---');
  w('');
}

w('## Reading a specimen');
w('');
w('Under every specimen in the catalogue:');
w('');
w('    SELECTOR   the element itself, with its classes');
w('    CONTEXT    the ancestor chain its CSS is scoped to');
w('    SOURCE     every stylesheet that contributes a rule');
w('    USED ON    the page it was taken from');
w('    MEASURED   box, padding, gap, radius at 1440×900');
w('');
/* read the count out of PAGE-SPECIFIC.md rather than repeating it here, so
   the two documents cannot drift apart on a number */
const PS = path.join(ROOT, 'design-system/gen11/PAGE-SPECIFIC.md');
const psN = fs.existsSync(PS)
  ? (/\*\*(\d+) page-specific families\*\*/.exec(fs.readFileSync(PS, 'utf8')) || [, '?'])[1]
  : '?';
w('If a component you need is not here, check `PAGE-SPECIFIC.md` — ' + psN + ' families');
w('occur on exactly one page and are recorded there rather than promoted into a');
w('shared abstraction that does not exist.');

fs.writeFileSync(OUT, L.join('\n'));
console.log('COMPONENTS.md', L.length, 'lines |', n, 'specimens');
